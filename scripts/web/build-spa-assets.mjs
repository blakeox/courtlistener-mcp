#!/usr/bin/env node

import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '../..');
const outDir = resolve(repoRoot, '.spa-dist');
const jsPath = resolve(outDir, 'app/spa.js');
const cssPath = resolve(outDir, 'app/spa.css');
const buildIdFile = resolve(repoRoot, 'src/web/spa-build-id.ts');
const DEFAULT_JS_BUDGET_BYTES = 790_000;
const DEFAULT_CSS_BUDGET_BYTES = 92 * 1024;
const MIN_VITE_NODE_MAJOR = 20;

function nodeMajorVersion() {
  return Number.parseInt(process.versions.node.split('.')[0], 10);
}

function readBudget(envName, defaultValue) {
  const raw = process.env[envName];
  if (!raw) {
    return defaultValue;
  }

  const parsed = Number.parseInt(raw, 10);
  if (Number.isNaN(parsed) || parsed <= 0) {
    throw new Error(`Invalid ${envName} value "${raw}". Expected a positive integer (bytes).`);
  }
  return parsed;
}

function formatKiB(bytes) {
  return `${(bytes / 1024).toFixed(2)} KiB`;
}

function runBuild() {
  execSync('./node_modules/.bin/vite build --config src/web-spa/vite.config.ts', {
    cwd: repoRoot,
    stdio: 'inherit',
  });
}

function main() {
  if (nodeMajorVersion() < MIN_VITE_NODE_MAJOR) {
    if (!existsSync(buildIdFile) || !existsSync(jsPath)) {
      throw new Error(
        `Node ${process.versions.node} cannot run the Vite SPA build (requires Node ${MIN_VITE_NODE_MAJOR}+). ` +
          'Run on Node 22+ or commit .spa-dist and src/web/spa-build-id.ts from CI.',
      );
    }
    console.log(
      `Skipping Vite SPA build on Node ${process.versions.node}; using committed .spa-dist and spa-build-id.`,
    );
    return;
  }

  runBuild();

  if (!existsSync(jsPath)) {
    throw new Error(`Missing SPA bundle at ${jsPath}. Check vite rollup output names.`);
  }

  const jsContent = readFileSync(jsPath, 'utf8');
  const cssContent = existsSync(cssPath) ? readFileSync(cssPath, 'utf8') : '';
  const jsBytes = Buffer.byteLength(jsContent, 'utf8');
  const cssBytes = Buffer.byteLength(cssContent, 'utf8');
  const jsBudget = readBudget('SPA_JS_BUDGET_BYTES', DEFAULT_JS_BUDGET_BYTES);
  const cssBudget = readBudget('SPA_CSS_BUDGET_BYTES', DEFAULT_CSS_BUDGET_BYTES);

  if (jsBytes > jsBudget || cssBytes > cssBudget) {
    const failures = [];
    if (jsBytes > jsBudget) {
      failures.push(
        `JS ${formatKiB(jsBytes)} > budget ${formatKiB(jsBudget)} (SPA_JS_BUDGET_BYTES)`,
      );
    }
    if (cssBytes > cssBudget) {
      failures.push(
        `CSS ${formatKiB(cssBytes)} > budget ${formatKiB(cssBudget)} (SPA_CSS_BUDGET_BYTES)`,
      );
    }

    throw new Error(
      `SPA payload budget exceeded:\n- ${failures.join('\n- ')}\n` +
        `Set SPA_JS_BUDGET_BYTES and/or SPA_CSS_BUDGET_BYTES to adjust thresholds.`,
    );
  }

  const buildId = createHash('sha256')
    .update(jsContent)
    .update('\n')
    .update(cssContent)
    .digest('hex')
    .slice(0, 16);

  const generated =
    `// Auto-generated by scripts/web/build-spa-assets.mjs\n` +
    `export const SPA_BUILD_ID = ${JSON.stringify(buildId)};\n`;

  let current = '';
  try {
    current = readFileSync(buildIdFile, 'utf8');
  } catch {
    current = '';
  }

  if (current !== generated) {
    writeFileSync(buildIdFile, generated, 'utf8');
  }

  console.log(`SPA assets in ${outDir} (JS ${formatKiB(jsBytes)}, CSS ${formatKiB(cssBytes)})`);
  console.log(`Wrote ${buildIdFile}`);
}

main();
