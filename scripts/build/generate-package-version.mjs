#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '../..');
const packageJsonPath = resolve(repoRoot, 'package.json');
const outFile = resolve(repoRoot, 'src/infrastructure/package-version.ts');

const packageJson = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
const version = packageJson.version ?? '0.0.0';

const generated =
  `// Auto-generated by scripts/build/generate-package-version.mjs\n` +
  `export const PACKAGE_VERSION = ${JSON.stringify(version)};\n`;

let current = '';
try {
  current = readFileSync(outFile, 'utf8');
} catch {
  current = '';
}

if (current !== generated) {
  writeFileSync(outFile, generated, 'utf8');
}

console.log(`Wrote ${outFile} (${version})`);
