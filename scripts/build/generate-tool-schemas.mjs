#!/usr/bin/env node

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const outputDir = resolve(repoRoot, 'src/server/generated');
const outputFile = resolve(outputDir, 'tool-input-schemas.ts');

process.env.COURTLISTENER_API_KEY ??= 'build-time-schema-generation';
process.env.MCP_ALLOW_DEV_FALLBACK ??= 'true';

const { bootstrapServices } = await import('../../src/infrastructure/bootstrap.ts');
const { container } = await import('../../src/infrastructure/container.ts');
const { z } = await import('zod/v4');

bootstrapServices();

const toolRegistry = container.get('toolRegistry');
const schemas = {};

for (const definition of toolRegistry.getToolDefinitions()) {
  schemas[definition.name] = definition.inputSchema;
}

mkdirSync(outputDir, { recursive: true });

const serialized = JSON.stringify(schemas, null, 2);
const source =
  `// Auto-generated by scripts/build/generate-tool-schemas.mjs — do not edit.\n` +
  `export const TOOL_INPUT_SCHEMAS: Readonly<Record<string, Record<string, unknown>>> = ` +
  `${serialized} as const;\n` +
  `export const TOOL_INPUT_SCHEMA_COUNT = ${Object.keys(schemas).length};\n`;

writeFileSync(outputFile, source, 'utf8');
console.log(`Generated ${outputFile} (${Object.keys(schemas).length} tools)`);

// Sanity: generation path uses native Zod v4 JSON Schema export.
if (typeof z.toJSONSchema !== 'function') {
  throw new Error('zod/v4 toJSONSchema is required for schema generation');
}

// Bootstrap registers cache/metrics timers; exit so build and CI gates do not hang.
process.exit(0);
