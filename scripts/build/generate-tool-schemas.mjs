#!/usr/bin/env node

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const outputDir = resolve(repoRoot, 'src/server/generated');
const inputOutputFile = resolve(outputDir, 'tool-input-schemas.ts');
const outputSchemaFile = resolve(outputDir, 'tool-output-schemas.ts');

process.env.COURTLISTENER_API_KEY ??= 'build-time-schema-generation';

const { bootstrapServices } = await import('../../src/infrastructure/bootstrap.ts');
const { container } = await import('../../src/infrastructure/container.ts');
const { getEnhancedToolDefinitions } = await import('../../src/tool-definitions.ts');
const {
  resolveToolOutputSchema,
  TOOL_OUTPUT_ASYNC_CANCEL,
  TOOL_OUTPUT_ASYNC_RESULT,
  TOOL_OUTPUT_ASYNC_STATUS,
} = await import('../../src/server/tool-output-schema-contract.ts');
const { MCP_ASYNC_CONTROL_TOOLS } = await import('../../src/server/async-tool-workflow.ts');
const { z } = await import('zod/v4');

bootstrapServices();

const toolRegistry = container.get('toolRegistry');
const inputSchemas = {};
const outputSchemas = {};

const enhancedOutputByName = new Map(
  getEnhancedToolDefinitions()
    .filter((tool) => tool.outputSchema !== undefined)
    .map((tool) => [tool.name, tool.outputSchema]),
);

for (const definition of toolRegistry.getToolDefinitions()) {
  inputSchemas[definition.name] = definition.inputSchema;
  outputSchemas[definition.name] = resolveToolOutputSchema(
    definition.name,
    enhancedOutputByName.get(definition.name),
  );
}

outputSchemas[MCP_ASYNC_CONTROL_TOOLS.status] = TOOL_OUTPUT_ASYNC_STATUS;
outputSchemas[MCP_ASYNC_CONTROL_TOOLS.result] = TOOL_OUTPUT_ASYNC_RESULT;
outputSchemas[MCP_ASYNC_CONTROL_TOOLS.cancel] = TOOL_OUTPUT_ASYNC_CANCEL;

mkdirSync(outputDir, { recursive: true });

const serializedInput = JSON.stringify(inputSchemas, null, 2);
const inputSource =
  `// Auto-generated by scripts/build/generate-tool-schemas.mjs — do not edit.\n` +
  `export const TOOL_INPUT_SCHEMAS: Readonly<Record<string, Record<string, unknown>>> = ` +
  `${serializedInput} as const;\n` +
  `export const TOOL_INPUT_SCHEMA_COUNT = ${Object.keys(inputSchemas).length};\n`;

writeFileSync(inputOutputFile, inputSource, 'utf8');
console.log(`Generated ${inputOutputFile} (${Object.keys(inputSchemas).length} tools)`);

const serializedOutput = JSON.stringify(outputSchemas, null, 2);
const outputSource =
  `// Auto-generated by scripts/build/generate-tool-schemas.mjs — do not edit.\n` +
  `import type { ToolOutputSchema } from '../tool-output-schema-contract.js';\n\n` +
  `export const TOOL_OUTPUT_SCHEMAS: Readonly<Record<string, ToolOutputSchema>> = ` +
  `${serializedOutput} as const;\n` +
  `export const TOOL_OUTPUT_SCHEMA_COUNT = ${Object.keys(outputSchemas).length};\n`;

writeFileSync(outputSchemaFile, outputSource, 'utf8');
console.log(`Generated ${outputSchemaFile} (${Object.keys(outputSchemas).length} tools)`);

if (typeof z.toJSONSchema !== 'function') {
  throw new Error('zod/v4 toJSONSchema is required for schema generation');
}

process.exit(0);
